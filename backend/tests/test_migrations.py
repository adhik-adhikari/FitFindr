def _test_database_url() -> str:
    database_url = os.getenv("FITFINDR_TEST_DATABASE_URL")
    if database_url is None:
        if os.getenv("CI"):
            pytest.fail("CI must configure FITFINDR_TEST_DATABASE_URL")
        pytest.skip("FITFINDR_TEST_DATABASE_URL is not configured")

    parsed = make_url(database_url)
    if parsed.database != EXPECTED_TEST_DATABASE:
        pytest.fail(f"integration tests require database {EXPECTED_TEST_DATABASE!r}")
    if os.getenv("FITFINDR_ALLOW_DESTRUCTIVE_TEST_DATABASE") != DESTRUCTIVE_OPT_IN:
        pytest.fail("destructive integration-test opt-in is missing")

    if "service" in parsed.query or os.getenv("PGSERVICE"):
        pytest.fail("integration tests refuse indirect libpq service targets")
    configured_targets = [parsed.host]
    configured_targets.extend(parsed.normalized_query.get("host", ()))
    configured_targets.extend(parsed.normalized_query.get("hostaddr", ()))
    if parsed.host is None:
        configured_targets.extend(
            value for value in (os.getenv("PGHOST"), os.getenv("PGHOSTADDR")) if value
        )
    for target in configured_targets:
        if target is None or target.startswith("/"):
            continue
        if target.lower() not in LOCAL_HOSTS:
            pytest.fail(
                "integration tests require a loopback or Unix-socket client target"
            )
    return database_url


def _assert_disposable_database(connection: psycopg.Connection) -> None:
    database_name, in_recovery, is_superuser = connection.execute(
        """
        SELECT current_database(), pg_is_in_recovery(), rolsuper
        FROM pg_roles WHERE rolname = current_user
        """
    ).fetchone()
    if database_name != EXPECTED_TEST_DATABASE:
        pytest.fail("connected database does not match the disposable test database")
    if in_recovery:
        pytest.fail("destructive tests refuse a replica/recovery server")
    if not is_superuser:
        pytest.fail("destructive tests require a local disposable superuser role")


def _drop_fixture_objects(connection: psycopg.Connection) -> None:
    connection.execute("DROP TABLE IF EXISTS public.garments")
    connection.execute("DROP TABLE IF EXISTS public.alembic_version")
    connection.execute("DROP TABLE IF EXISTS public.provider_managed_sentinel")
    for schema_name in ("auth", "storage", "realtime", "vault", "extensions"):
        connection.execute(
            sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(
                sql.Identifier(schema_name)
            )
        )


def _prepare_managed_dependencies(database_url: str) -> None:
    with psycopg.connect(database_url, autocommit=True) as connection:
        _assert_disposable_database(connection)
        _drop_fixture_objects(connection)
        connection.execute(
            """
            DO $$
            BEGIN
                IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'anon') THEN
                    CREATE ROLE anon NOLOGIN;
                END IF;
                IF NOT EXISTS (
                    SELECT FROM pg_roles WHERE rolname = 'authenticated'
                ) THEN
                    CREATE ROLE authenticated NOLOGIN;
                END IF;
            END
            $$
            """
        )
        connection.execute("GRANT USAGE ON SCHEMA public TO anon, authenticated")
        connection.execute(
            """
            ALTER DEFAULT PRIVILEGES IN SCHEMA public
            GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES
            TO anon, authenticated
            """
        )
        for schema_name, table_name in (
            ("auth", "users"),
            ("storage", "objects"),
            ("realtime", "messages"),
            ("vault", "secrets"),
            ("extensions", "provider_objects"),
        ):
            connection.execute(
                sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(schema_name))
            )
            connection.execute(
                sql.SQL("CREATE TABLE {}.{} (id uuid PRIMARY KEY)").format(
                    sql.Identifier(schema_name),
                    sql.Identifier(table_name),
                )
            )
        connection.execute(
            "CREATE TABLE public.provider_managed_sentinel (id uuid PRIMARY KEY)"
        )
        initial_privileges = connection.execute(
            """
            SELECT
                has_table_privilege(
                    'anon', 'public.provider_managed_sentinel', 'SELECT'
                ),
                has_table_privilege(
                    'authenticated', 'public.provider_managed_sentinel', 'INSERT'
                )
            """
        ).fetchone()
        assert initial_privileges == (True, True)


def _clean_application_schema(database_url: str) -> None:
    with psycopg.connect(database_url, autocommit=True) as connection:
        _assert_disposable_database(connection)
        connection.execute(
            """
            ALTER DEFAULT PRIVILEGES IN SCHEMA public
            REVOKE ALL PRIVILEGES ON TABLES FROM anon, authenticated
            """
        )
        _drop_fixture_objects(connection)


def _alembic_config() -> Config:
    return Config(str(BACKEND_DIR / "alembic.ini"))


def _insert_garment(
    connection: psycopg.Connection,
    user_id: UUID,
    **values,
) -> UUID:
    garment_id = values.pop("id", uuid4())
    row = {"id": garment_id, "user_id": user_id, **values}
    query = sql.SQL("INSERT INTO public.garments ({}) VALUES ({})").format(
        sql.SQL(", ").join(map(sql.Identifier, row)),
        sql.SQL(", ").join(sql.Placeholder() for _ in row),
    )
    connection.execute(query, tuple(row.values()))
    return garment_id


def _assert_check_violation(
    connection: psycopg.Connection,
    expected_constraint: str,
    user_id: UUID,
    **values,
) -> None:
    with pytest.raises(psycopg.errors.CheckViolation) as caught:
        _insert_garment(connection, user_id, **values)
    assert caught.value.diag.constraint_name == expected_constraint


def _assert_role_cannot_read_or_write(
    connection: psycopg.Connection,
    role: str,
) -> None:
    connection.execute(sql.SQL("SET ROLE {}").format(sql.Identifier(role)))
    try:
        with pytest.raises(psycopg.errors.InsufficientPrivilege):
            connection.execute("SELECT * FROM public.garments")
        with pytest.raises(psycopg.errors.InsufficientPrivilege):
            connection.execute(
                "INSERT INTO public.garments (id, user_id) VALUES (%s, %s)",
                (uuid4(), uuid4()),
            )
    finally:
        connection.execute("RESET ROLE")


def _exercise_runtime_and_none_as_sql_null(
    database_url: str,
    user_id: UUID,
) -> tuple[UUID, UUID]:
    settings = DatabaseSettings(_env_file=None, database_url=database_url)
    runtime = DatabaseRuntime()
    rolled_back_id = uuid4()
    committed_id = uuid4()

    async def exercise() -> None:
        assert not runtime.initialized
        async with runtime.session(settings) as first_session:
            first_session.add(Garment(id=rolled_back_id, user_id=user_id))
            await first_session.flush()
        assert runtime.initialized

        async with runtime.session() as second_session:
            assert second_session is not first_session
            second_session.add(
                Garment(
                    id=committed_id,
                    user_id=user_id,
                    analysis_proposal=None,
                )
            )
            await second_session.commit()

        await runtime.dispose()
        assert not runtime.initialized

    asyncio.run(exercise())
    return rolled_back_id, committed_id


def test_garments_migration_and_postgresql_invariants(monkeypatch) -> None:
    database_url = _test_database_url()
    _prepare_managed_dependencies(database_url)
    monkeypatch.setenv("DATABASE_URL", database_url)

    try:
        config = _alembic_config()
        command.upgrade(config, "head")
        # Managed schemas and public non-application tables exist here. A clean
        # check demonstrates that Alembic does not claim ownership of them.
        command.check(config)

        with psycopg.connect(database_url, autocommit=True) as connection:
            columns = {
                row[0]
                for row in connection.execute(
                    """
                    SELECT column_name
                    FROM information_schema.columns
                    WHERE table_schema = 'public' AND table_name = 'garments'
                    """
                )
            }
            assert columns == EXPECTED_COLUMNS

            constraints = {
                row[0]
                for row in connection.execute(
                    """
                    SELECT conname
                    FROM pg_constraint
                    WHERE conrelid = 'public.garments'::regclass
                      AND contype = 'c'
                    """
                )
            }
            assert constraints == EXPECTED_CHECKS

            indexes = {
                row[0]: row[1]
                for row in connection.execute(
                    """
                    SELECT c.relname, pg_get_expr(i.indpred, i.indrelid)
                    FROM pg_index AS i
                    JOIN pg_class AS c ON c.oid = i.indexrelid
                    WHERE i.indrelid = 'public.garments'::regclass
                    """
                )
            }
            assert "ix_garments_user_status_category" in indexes
            predicate = indexes["ix_garments_active_available_user_category"]
            assert predicate is not None
            assert all(
                token in predicate.lower()
                for token in ("status", "active", "is_available", "true")
            )
            assert not any("image_key" in index_name for index_name in indexes)

            foreign_key = connection.execute(
                """
                SELECT conname, confdeltype, confrelid::regclass::text
                FROM pg_constraint
                WHERE conrelid = 'public.garments'::regclass
                  AND contype = 'f'
                """
            ).fetchone()
            assert foreign_key == (
                "fk_garments_user_id_users",
                "c",
                "auth.users",
            )

            rls_state = connection.execute(
                """
                SELECT relrowsecurity, relforcerowsecurity
                FROM pg_class
                WHERE oid = 'public.garments'::regclass
                """
            ).fetchone()
            assert rls_state == (True, False)
            policy_count = connection.execute(
                """
                SELECT count(*)
                FROM pg_policies
                WHERE schemaname = 'public' AND tablename = 'garments'
                """
            ).fetchone()
            assert policy_count == (0,)

            privilege_checks = connection.execute(
                """
                SELECT role_name, privilege,
                       has_table_privilege(
                           role_name, 'public.garments', privilege
                       )
                FROM unnest(ARRAY['anon', 'authenticated']) AS role_name
                CROSS JOIN unnest(
                    ARRAY['SELECT', 'INSERT', 'UPDATE', 'DELETE']
                ) AS privilege
                """
            ).fetchall()
            assert privilege_checks
            assert all(not has_privilege for _, _, has_privilege in privilege_checks)
            _assert_role_cannot_read_or_write(connection, "anon")
            _assert_role_cannot_read_or_write(connection, "authenticated")

            user_id = uuid4()
            connection.execute("INSERT INTO auth.users (id) VALUES (%s)", (user_id,))

            partial_draft_id = _insert_garment(
                connection,
                user_id,
                image_key="private/draft.jpg",
                category="top",
            )
            partial_draft = connection.execute(
                """
                SELECT status, garment_type, primary_color,
                       secondary_colors, style_tags, custom_tags,
                       is_favorite, is_available
                FROM public.garments WHERE id = %s
                """,
                (partial_draft_id,),
            ).fetchone()
            assert partial_draft == ("draft", None, None, [], [], [], False, True)

            _assert_check_violation(
                connection,
                "ck_garments_status_valid",
                user_id,
                status="archived",
            )
            _assert_check_violation(
                connection,
                "ck_garments_category_valid",
                user_id,
                category="dress",
            )

            active_values = {
                "status": "active",
                "image_key": "private/active.jpg",
                "category": "top",
                "garment_type": "hoodie",
                "primary_color": "navy",
            }
            for field in ("image_key", "category", "garment_type", "primary_color"):
                values = {**active_values, field: None}
                _assert_check_violation(
                    connection,
                    "ck_garments_active_required_fields",
                    user_id,
                    **values,
                )
            for field in ("image_key", "garment_type", "primary_color"):
                values = {**active_values, field: " \t\n"}
                _assert_check_violation(
                    connection,
                    "ck_garments_active_required_fields",
                    user_id,
                    **values,
                )
            for category_value in ("", " \t\n"):
                _assert_check_violation(
                    connection,
                    "ck_garments_category_valid",
                    user_id,
                    **{**active_values, "category": category_value},
                )

            for field, constraint_name in (
                ("image_key", "ck_garments_image_key_nonblank"),
                ("garment_type", "ck_garments_garment_type_nonblank"),
                ("primary_color", "ck_garments_primary_color_nonblank"),
            ):
                for blank_value in ("", " \t\n"):
                    _assert_check_violation(
                        connection,
                        constraint_name,
                        user_id,
                        **{field: blank_value},
                    )

            analysis_constraint = "ck_garments_analysis_complete"
            analysis_cases = [
                {"analysis_proposal": Jsonb({"garment": None})},
                {
                    "analysis_provider": "provider",
                    "analysis_model": "model",
                    "analysis_schema_version": 1,
                    "analyzed_at": datetime.now(UTC),
                },
                {
                    "analysis_proposal": Jsonb({}),
                    "analysis_provider": " \t\n",
                    "analysis_model": "model",
                    "analysis_schema_version": 1,
                    "analyzed_at": datetime.now(UTC),
                },
                {
                    "analysis_proposal": Jsonb({}),
                    "analysis_provider": "provider",
                    "analysis_model": "model",
                    "analysis_schema_version": 0,
                    "analyzed_at": datetime.now(UTC),
                },
            ]
            for proposal in (Jsonb(None), Jsonb([]), Jsonb("not-an-object")):
                analysis_cases.append(
                    {
                        "analysis_proposal": proposal,
                        "analysis_provider": "provider",
                        "analysis_model": "model",
                        "analysis_schema_version": 1,
                        "analyzed_at": datetime.now(UTC),
                    }
                )
            for analysis_values in analysis_cases:
                _assert_check_violation(
                    connection,
                    analysis_constraint,
                    user_id,
                    **analysis_values,
                )

            with pytest.raises(psycopg.errors.ForeignKeyViolation) as caught:
                _insert_garment(connection, uuid4())
            assert caught.value.diag.constraint_name == "fk_garments_user_id_users"

            active_id = _insert_garment(connection, user_id, **active_values)
            active = connection.execute(
                """
                SELECT pattern, formality, warmth, material, sleeve_length,
                       neckline, fit, note, analysis_proposal
                FROM public.garments WHERE id = %s
                """,
                (active_id,),
            ).fetchone()
            assert active == (None,) * 9

            valid_proposal = {
                "image_assessment": {"usable": True, "issue": None},
                "garment": None,
            }
            analyzed_at = datetime.now(UTC)
            analyzed_draft_id = _insert_garment(
                connection,
                user_id,
                analysis_proposal=Jsonb(valid_proposal),
                analysis_provider="test-provider",
                analysis_model="test-model",
                analysis_schema_version=1,
                analyzed_at=analyzed_at,
            )
            analyzed_draft = connection.execute(
                """
                SELECT jsonb_typeof(analysis_proposal), analysis_provider,
                       analysis_model, analysis_schema_version,
                       analyzed_at IS NOT NULL
                FROM public.garments WHERE id = %s
                """,
                (analyzed_draft_id,),
            ).fetchone()
            assert analyzed_draft == (
                "object",
                "test-provider",
                "test-model",
                1,
                True,
            )

        rolled_back_id, committed_id = _exercise_runtime_and_none_as_sql_null(
            database_url, user_id
        )
        with psycopg.connect(database_url) as connection:
            persistence = connection.execute(
                """
                SELECT
                    EXISTS(SELECT 1 FROM public.garments WHERE id = %s),
                    EXISTS(
                        SELECT 1 FROM public.garments
                        WHERE id = %s AND analysis_proposal IS NULL
                    )
                """,
                (rolled_back_id, committed_id),
            ).fetchone()
            assert persistence == (False, True)

        with psycopg.connect(database_url, autocommit=True) as connection:
            connection.execute(
                "ALTER TABLE public.garments ALTER COLUMN status SET DEFAULT 'active'"
            )
        try:
            with pytest.raises(AutogenerateDiffsDetected):
                command.check(config)
        finally:
            with psycopg.connect(database_url, autocommit=True) as connection:
                connection.execute(
                    "ALTER TABLE public.garments ALTER COLUMN status SET DEFAULT 'draft'"
                )
        command.check(config)

        with psycopg.connect(database_url, autocommit=True) as connection:
            connection.execute("DELETE FROM auth.users WHERE id = %s", (user_id,))
            remaining = connection.execute(
                "SELECT count(*) FROM public.garments WHERE user_id = %s",
                (user_id,),
            ).fetchone()
            assert remaining == (0,)

        command.downgrade(config, "base")
        with psycopg.connect(database_url) as connection:
            assert connection.execute(
                "SELECT to_regclass('public.garments')"
            ).fetchone() == (None,)
            for managed_table in MANAGED_FIXTURE_TABLES:
                assert (
                    connection.execute(
                        "SELECT to_regclass(%s)", (managed_table,)
                    ).fetchone()[0]
                    is not None
                )

        command.upgrade(config, "head")
    finally:
        _clean_application_schema(database_url)
